#pragma once
// Общие уровни тревоги для всех подсистем. Уровень базы = максимум по подсистемам,
// поэтому порядок значений важен: чем больше число, тем серьёзнее.
#include <stdint.h>

enum AlarmLevel : uint8_t {
  LVL_OK    = 0,  // НОРМА
  LVL_WARN  = 1,  // ВНИМАНИЕ
  LVL_ALARM = 2,  // АВАРИЯ
};
